export type Locale = "da" | "en";

let locale: Locale = "da";
if (process.env["LCC_LANG"]?.startsWith("en")) locale = "en";

export function setLocale(lang: string): void {
  locale = lang.startsWith("en") ? "en" : "da";
}

export function getLocale(): Locale {
  return locale;
}

export function confirmYes(answer: string): boolean {
  const a = answer.trim().toLowerCase();
  return locale === "en" ? (a === "y" || a === "yes") : (a === "j" || a === "ja");
}

export function confirmHint(): string {
  return locale === "en" ? "y/n" : "j/n";
}

